def normalize_mac(value: str) -> str:
    raw = "".join(ch for ch in (value or "").lower() if ch in "0123456789abcdef")
    if len(raw) < 12:
        return ""
    raw = raw[:12]
    return ":".join(raw[i : i + 2] for i in range(0, 12, 2))


def vendor_for_mac(mac: str) -> str:
    compact = "".join(ch for ch in (mac or "").lower() if ch in "0123456789abcdef")
    if len(compact) < 6:
        return ""
    return OUI_VENDORS.get(compact[:6], "")
